import { Dataset, QueryResult } from "@/shared/types";
import { AIPromptContext, AIPromptColumn, AIResponse } from "./types";
import { callLLM } from "./llmService";
import { useUiStore } from "@/store/uiStore";
import { queryEngine } from "@/shared/services/queryEngine";
import { formulaEngine } from "@/shared/services/formulaEngine";
import { useFilterStore } from "@/store/filterStore";
import { useChartStore } from "@/store/chartStore";

export class AiEngineError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "AiEngineError";
  }
}

export const aiEngine = {
  /**
   * Constructs prompt context from active dataset
   */
  buildContext(dataset: Dataset, prompt: string): AIPromptContext {
    const columns: AIPromptColumn[] = (dataset.metadata?.columns || []).map((c) => {
      const sampleVals = dataset.data
        .slice(0, 5)
        .map((r) => String(r[c.name]))
        .filter((v) => v !== "null" && v !== "undefined");

      return {
        name: c.name,
        type: c.inferredDataType,
        sampleValues: sampleVals,
        minimumValue: c.minimumValue,
        maximumValue: c.maximumValue,
        uniqueValueCount: c.uniqueValueCount,
      };
    });

    // Fallback if metadata is not populated
    const resolvedColumns =
      columns.length > 0
        ? columns
        : dataset.columns.map((col) => {
            const sampleVals = dataset.data
              .slice(0, 5)
              .map((r) => String(r[col]))
              .filter((v) => v !== "null" && v !== "undefined");
            return {
              name: col,
              type: dataset.columnTypes[col] || "categorical",
              sampleValues: sampleVals,
            };
          });

    return {
      prompt,
      datasetName: dataset.name,
      columns: resolvedColumns,
      metadata: dataset.metadata,
      calculatedFields: dataset.calculatedFields || [],
    };
  },

  /**
   * Cleans JSON response string by stripping code fences
   */
  cleanJsonString(raw: string): string {
    let clean = raw.trim();
    if (clean.startsWith("```json")) {
      clean = clean.replace(/^```json/, "").replace(/```$/, "").trim();
    } else if (clean.startsWith("```")) {
      clean = clean.replace(/^```/, "").replace(/```$/, "").trim();
    }
    return clean;
  },

  /**
   * Generates AI query or formula with strict validation
   */
  async generateQueryOrFormula(
    prompt: string,
    dataset: Dataset | null,
    mode?: "query" | "formula"
  ): Promise<AIResponse> {
    if (!dataset) {
      throw new AiEngineError("No active dataset selected. Please upload or select a dataset first.");
    }

    const { llmApiKey, llmProvider } = useUiStore.getState();
    const context = this.buildContext(dataset, prompt);

    const rawResponse = await callLLM(llmApiKey, llmProvider, context, mode);

    let parsed: AIResponse;
    try {
      const cleanJson = this.cleanJsonString(rawResponse);
      parsed = JSON.parse(cleanJson);
    } catch (e) {
      console.error("AI JSON Parse Error:", e, rawResponse);
      throw new AiEngineError("AI generated an invalid query. Please rephrase.");
    }

    // Validate columns if type is query
    if (parsed.type === "query" && parsed.query) {
      this.validateQueryColumns(dataset, parsed.query);
    }

    return parsed;
  },

  /**
   * Validates that all suggested columns actually exist in the dataset
   */
  validateQueryColumns(dataset: Dataset, query: NonNullable<AIResponse["query"]>): void {
    const existingColNames = new Set([
      ...dataset.columns,
      ...(dataset.calculatedFields || []).map((f) => f.name),
    ]);

    const existingLowerNames = new Set(Array.from(existingColNames).map((c) => c.toLowerCase()));

    // The LLM-generated query is untyped JSON with no runtime shape guarantee - a missing
    // `alias`/`column`/`operator` (routine for an LLM to omit) would otherwise throw a raw
    // TypeError from deep inside this method and surface as-is in a user-facing toast.
    // Validate shape up front and fail with a clean, actionable message instead.
    if (query.aggregations) {
      for (const agg of query.aggregations) {
        if (
          !agg ||
          typeof agg !== "object" ||
          typeof agg.column !== "string" || agg.column.trim() === "" ||
          typeof agg.operator !== "string" || agg.operator.trim() === "" ||
          typeof agg.alias !== "string" || agg.alias.trim() === ""
        ) {
          throw new AiEngineError(
            "AI generated an invalid query. An aggregation is missing a required field (column, operator, or alias). Please rephrase."
          );
        }
      }
    }

    // Collect alias names generated by aggregations
    const aggAliases = new Set(
      (query.aggregations || []).map((a) => a.alias.toLowerCase())
    );

    const checkColumn = (col?: string, allowAggAlias = false) => {
      if (!col) return;
      const lower = col.toLowerCase();
      if (!existingLowerNames.has(lower)) {
        if (allowAggAlias && aggAliases.has(lower)) {
          return;
        }
        throw new AiEngineError(`AI generated an invalid query. Column '${col}' does not exist in dataset. Please rephrase.`);
      }
    };

    // 1. GroupBy column check
    if (query.groupBy?.column) {
      checkColumn(query.groupBy.column);
    }

    // 2. Aggregation columns check
    if (query.aggregations) {
      for (const agg of query.aggregations) {
        checkColumn(agg.column);
      }
    }

    // 3. Filter condition columns check
    if (query.filters?.conditions) {
      for (const cond of query.filters.conditions) {
        checkColumn(cond.column);
      }
    }

    // 4. Categorical filters check
    if (query.filters?.categoricalFilters) {
      for (const col of Object.keys(query.filters.categoricalFilters)) {
        checkColumn(col);
      }
    }

    // 5. Date range filters check
    if (query.filters?.dateRangeFilters) {
      for (const col of Object.keys(query.filters.dateRangeFilters)) {
        checkColumn(col);
      }
    }

    // 6. Sorting check
    if (query.sorting) {
      for (const sort of query.sorting) {
        checkColumn(sort.column, true);
      }
    }
  },

  /**
   * Generates and runs an AI query against `dataset`, returning the result for the
   * caller to preview. Read-only — does NOT touch filterStore/chartStore. The caller
   * must call `applyAIQueryResult` to actually commit the result (filter the active
   * view, auto-create a chart), so a generated-but-unreviewed query can't silently
   * overwrite the user's current filtered view or spawn a stray chart.
   */
  async generateAIQueryPreview(
    prompt: string,
    dataset: Dataset
  ): Promise<{ response: AIResponse; queryResult: QueryResult }> {
    const response = await this.generateQueryOrFormula(prompt, dataset, "query");

    if (!response.query) {
      throw new AiEngineError("AI did not produce a valid query structure.");
    }

    const queryResult = queryEngine.execute(dataset, response.query);

    return { response, queryResult };
  },

  /**
   * Commits a previously-previewed AI query result: applies it to filterStore and, if
   * a chart type was suggested, auto-creates a chart. Call only once the user has
   * reviewed and accepted the preview from `generateAIQueryPreview`.
   */
  applyAIQueryResult(
    prompt: string,
    response: AIResponse,
    queryResult: QueryResult,
    dataset: Dataset
  ): void {
    if (!response.query) {
      throw new AiEngineError("AI did not produce a valid query structure.");
    }

    useFilterStore.getState().setFilteredData(queryResult.rows);

    if (response.chartType) {
      const groupByCol = response.query.groupBy?.column;
      const aggCol = response.query.aggregations?.[0]?.alias || response.query.aggregations?.[0]?.column;

      useChartStore.getState().createChart({
        id: `ai-chart-${Date.now()}`,
        type: response.chartType,
        title: response.title || `${prompt} (${response.chartType})`,
        xAxis: groupByCol || dataset.columns[0],
        yAxis: aggCol || dataset.columns[1] || dataset.columns[0],
        groupBy: groupByCol,
        data: queryResult.rows,
        datasetId: dataset.id,
      });
    }
  },

  /**
   * Generates a formula string from natural language prompt
   */
  async generateFormula(
    prompt: string,
    dataset: Dataset
  ): Promise<{ formula: string; fieldName: string; explanation?: string }> {
    const response = await this.generateQueryOrFormula(prompt, dataset, "formula");

    if (!response.formula) {
      throw new AiEngineError("AI failed to generate a valid formula expression.");
    }

    const fieldName = response.fieldName || "AI_Calculated_Field";

    // Validate formula with formulaEngine
    const existingColumns = dataset.columns;
    const calculatedFields = dataset.calculatedFields || [];

    const errors = formulaEngine.validate(
      fieldName,
      response.formula,
      existingColumns,
      calculatedFields
    );

    if (errors.length > 0) {
      const msg = errors.map((e) => e.message).join(" ");
      throw new AiEngineError(`Generated formula validation error: ${msg}`);
    }

    return {
      formula: response.formula,
      fieldName,
      explanation: response.explanation,
    };
  },
};
