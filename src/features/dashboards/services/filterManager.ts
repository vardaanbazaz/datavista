import { Query, GlobalFilter, Dataset, FilterCondition } from "@/shared/types";

export const filterManager = {
  /**
   * Merges active global/cross-filters into a widget's query configuration.
   * Ensures that the widget's own cross-filter is ignored to prevent self-filtering out of context.
   */
  merge(
    widgetQuery: Query,
    activeGlobalFilters: GlobalFilter[],
    widgetId?: string,
    dataset?: Dataset
  ): Query {
    // Deep clone to ensure we do not mutate the cached/stored query configuration
    const mergedQuery: Query = JSON.parse(JSON.stringify(widgetQuery));

    if (!mergedQuery.filters) {
      mergedQuery.filters = {};
    }
    if (!mergedQuery.filters.conditions) {
      mergedQuery.filters.conditions = [];
    }

    activeGlobalFilters.forEach((gf) => {
      // 1. Skip if the filter was generated by this specific widget (prevents self-filtering out of context)
      if (widgetId && gf.sourceWidgetId === widgetId) {
        return;
      }

      // 2. Check dataset context compatibility
      let isApplicable = false;
      if (dataset) {
        // Same dataset source
        if (gf.datasetId === dataset.id) {
          isApplicable = true;
        }
        // Cross-dataset filtering via linked datasets
        else if (gf.linkedDatasets && gf.linkedDatasets.includes(dataset.id)) {
          isApplicable = true;
        }
        // Fallback for global filters with no datasetId
        else if (!gf.datasetId) {
          isApplicable = true;
        }

        // 3. Make sure the column exists in the target dataset
        const columnExists = dataset.columns.includes(gf.column);
        if (isApplicable && !columnExists) {
          isApplicable = false;
        }
      } else {
        isApplicable = true;
      }

      if (isApplicable) {
        // Check if there is already an identical condition to avoid duplicates in hash
        const isDuplicate = mergedQuery.filters.conditions!.some(
          (c) =>
            c.column === gf.column &&
            c.operator === gf.operator &&
            JSON.stringify(c.value) === JSON.stringify(gf.value)
        );

        if (!isDuplicate) {
          const condition: FilterCondition = {
            column: gf.column,
            operator: gf.operator,
            value: gf.value,
          };
          mergedQuery.filters.conditions!.push(condition);
        }
      }
    });

    return mergedQuery;
  },
};
